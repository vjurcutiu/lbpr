// Debug helper: context-menu instrumentation
// Enable by adding ?debugCtxMenu=1 to the URL or running:
//   localStorage.setItem('lbp.debug.ctxmenu','1'); location.reload();
const DEBUG_CTXMENU = (() => {
  if (typeof window === "undefined") return false
  try {
    const sp = new URLSearchParams(window.location.search)
    const qp = (sp.get("debugCtxMenu") || "").toLowerCase()
    if (qp === "1" || qp === "true" || qp === "yes") return true
    return window.localStorage.getItem("lbp.debug.ctxmenu") === "1"
  } catch {
    return false
  }
})()

function dbg(scope: string, payload?: any) {
  if (!DEBUG_CTXMENU) return
  try {
    // eslint-disable-next-line no-console
    console.debug(`[ctxmenu.ui] ${scope}`, payload ?? "")
  } catch {
    // no-op
  }
}

function elInfo(el: any) {
  const t = el as HTMLElement | null
  if (!t || typeof t !== "object") return null
  return {
    tag: (t as any).tagName,
    id: (t as any).id,
    className: (t as any).className,
    dataset: { ...(((t as any).dataset as any) || {}) },
    text: typeof (t as any).textContent === "string" ? (t as any).textContent?.trim()?.slice(0, 80) : undefined,
  }
}

